"""Offline development tool: render canonical SVG into hash-bound local assets.

CairoSVG/Pillow are build tools only. The desktop host loads the generated bytes
without importing a renderer, downloading a resource, or starting a process.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
import io
import json
import math
from pathlib import Path
import re
import struct
import xml.etree.ElementTree as ET
import zlib

SVG = 'http://www.w3.org/2000/svg'
SIZES = (16, 24, 32, 256)
NAMES = {**{'mark' + str(n): 'icon-' + str(n) + '.png' for n in SIZES},
         'tray32': 'tray-32.png', 'app256': 'app-256.png'}
PAINT = {'linearGradient', 'radialGradient', 'stop'}
ALLOWED = {'svg', 'g', 'path', 'circle', 'ellipse', 'rect', 'line', 'polyline',
           'polygon', 'defs', *PAINT}
ET.register_namespace('', SVG)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_tree(data: bytes):
    if not data or len(data) > 32768 or re.search(br'<!DOCTYPE|<!ENTITY', data, re.I):
        raise ValueError('A bounded local vector source is required')
    root = ET.fromstring(data)
    nodes = list(root.iter())
    if root.tag != '{' + SVG + '}svg' or len(nodes) > 128:
        raise ValueError('A simple local SVG is required')
    for element in nodes:
        if element.tag.split('}')[-1] not in ALLOWED or any(
            key.split('}')[-1].lower().startswith('on') or key.split('}')[-1] in ('href', 'style')
            for key in element.attrib):
            raise ValueError('External resources, scripts, fonts and embedded images are not allowed')
        if any(re.search(r'url\(\s*(?!#[A-Za-z_])["\']?[^)]', value, re.I) for value in element.attrib.values()):
            raise ValueError('Only local paint references are allowed')
    try:
        box = tuple(float(value) for value in root.attrib['viewBox'].split())
    except (KeyError, ValueError) as error:
        raise ValueError('A square viewBox is required') from error
    if len(box) != 4 or not (box[2] == box[3] and 0 < box[2] <= 4096):
        raise ValueError('A square viewBox is required')
    return root, box


def monochrome(root):
    result = deepcopy(root)
    for parent in list(result.iter()):
        for child in list(parent):
            if child.tag.split('}')[-1] in PAINT:
                parent.remove(child)
    for element in result.iter():
        element.attrib.pop('color', None)
        for key in ('fill', 'stroke'):
            if key in element.attrib and element.attrib[key] != 'none':
                element.set(key, 'currentColor')
    result.set('fill', 'currentColor')
    return ET.tostring(result, encoding='utf-8') + b'\n'


def render_tree(root):
    result = deepcopy(root)
    # CairoSVG 2.8 does not implement SVG pathLength normalization. Convert
    # circles to equivalent physical dash lengths without changing the source.
    for element in result.iter():
        if 'pathLength' not in element.attrib:
            continue
        if element.tag.split('}')[-1] != 'circle':
            raise ValueError('Declared pathLength currently requires a circle; do not render a different shape silently')
        declared = float(element.attrib.pop('pathLength'))
        if not math.isfinite(declared) or declared <= 0:
            raise ValueError('Invalid declared path length')
        scale = 2 * math.pi * float(element.attrib['r']) / declared
        for key in ('stroke-dasharray', 'stroke-dashoffset'):
            if key in element.attrib:
                element.set(key, ' '.join(str(float(value) * scale) for value in element.attrib[key].replace(',', ' ').split()))
    return result


def png(image) -> bytes:
    """Deterministic RGBA/filter-0 PNG: no metadata, fonts or extra codec."""
    image = image.convert('RGBA')
    width, height = image.size
    raw = image.tobytes()
    scanlines = b''.join(b'\0' + raw[y * width * 4:(y + 1) * width * 4] for y in range(height))
    def chunk(kind, payload):
        return struct.pack('>I', len(payload)) + kind + payload + struct.pack('>I', zlib.crc32(kind + payload) & 0xffffffff)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(scanlines, 9)) + chunk(b'IEND', b'')


def build(root: Path, plate: str = 'graphite'):
    if plate not in ('graphite', 'silver'):
        raise ValueError('Unknown plate style')
    root = Path(root)
    if root.is_symlink():
        raise ValueError('A real asset directory is required')
    source = root / 'icon.svg'
    if source.is_symlink():
        raise ValueError('The canonical source must not be symbolic')
    data = source.read_bytes()
    tree, box = source_tree(data)
    # Import optional build dependencies only here; runtime never imports them.
    import cairosvg
    import cairocffi
    from PIL import Image
    import PIL
    generated = {'icon-monochrome.svg': monochrome(tree)}
    def render(raw, size):
        # A bounded build-only supersample keeps small diagonals and curves clean.
        image = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=raw, output_width=size * 4, output_height=size * 4, unsafe=False))).convert('RGBA')
        return image.resize((size, size), Image.Resampling.LANCZOS)
    visible = render_tree(tree)
    visible.set('color', '#36393c')
    visible_bytes = ET.tostring(visible, encoding='utf-8')
    assets = {}
    for size in SIZES:
        name = NAMES['mark' + str(size)]
        generated[name] = png(render(visible_bytes, size))
        assets['mark' + str(size)] = {'path': name, 'width': size, 'height': size}
    for role, size in [('tray32', 32), ('app256', 256)]:
        background = render_tree(tree)
        background.set('color', '#f5f6f8' if plate == 'graphite' else '#36393c')
        paper = '#36393c' if plate == 'graphite' else '#f5f6f8'
        x, y, width, height = box
        if role == 'tray32':
            node = ET.Element('{' + SVG + '}circle', {'cx': str(x + width / 2), 'cy': str(y + height / 2), 'r': str(width * .484375), 'fill': paper})
        else:
            node = ET.Element('{' + SVG + '}rect', {'x': str(x), 'y': str(y), 'width': str(width), 'height': str(height), 'rx': str(width / 4), 'fill': paper})
        background.insert(0, node)
        name = NAMES[role]
        generated[name] = png(render(ET.tostring(background, encoding='utf-8'), size))
        assets[role] = {'path': name, 'width': size, 'height': size}
    for value in assets.values():
        value.update({'sha256': sha(generated[value['path']]), 'bytes': len(generated[value['path']])})
    manifest = {'schema_version': 1, 'source': {'path': 'icon.svg', 'sha256': sha(data), 'bytes': len(data)},
                'monochrome': {'path': 'icon-monochrome.svg', 'sha256': sha(generated['icon-monochrome.svg']), 'bytes': len(generated['icon-monochrome.svg'])},
                'assets': assets, 'generator': {'name': 'CairoSVG', 'version': cairosvg.__version__, 'cairo': cairocffi.cairo_version_string(), 'pillow': PIL.__version__, 'runtime_dependency': False, 'oversampling': 4, 'plate': plate, 'circle_pathLength_normalized': any('pathLength' in node.attrib for node in tree.iter())}}
    manifest_path = root / 'icon-assets.json'
    previous = None
    if manifest_path.exists():
        if manifest_path.is_symlink():
            raise ValueError('The generated manifest must not be symbolic')
        previous = json.loads(manifest_path.read_bytes())
    prior = {v['path']: v for v in [*(previous or {}).get('assets', {}).values(), *([(previous or {})['monochrome']] if (previous or {}).get('monochrome') else [])]}
    # Never overwrite an unrelated or manually edited file. An intentional SVG
    # update can regenerate only bytes still bound to the last generated manifest.
    for name, value in generated.items():
        target = root / name
        if target.is_symlink() or target.exists() and target.read_bytes() != value and (
                name not in prior or sha(target.read_bytes()) != prior[name]['sha256']):
            raise ValueError('Generated asset drift; preserve and inspect: ' + name)
    for name, value in generated.items():
        (root / name).write_bytes(value)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--plate', choices=('graphite', 'silver'), default='graphite')
    args = parser.parse_args()
    print(json.dumps(build(args.root, args.plate), ensure_ascii=False, indent=2))
