from urllib.parse import parse_qs, urlparse

from playwright.sync_api import sync_playwright, expect
from test_web import launch_browser, open_project_form


def test_ui_create_start_real_mock_events_refresh_and_reconnect_without_duplicates(live_server):
    with sync_playwright() as playwright:
        browser = launch_browser(playwright)
        context = browser.new_context()
        page = context.new_page()
        errors = []
        event_requests = []
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.on("request", lambda request: event_requests.append(request.url) if "/events?" in request.url else None)
        page.goto(live_server.origin)
        open_project_form(page)
        page.locator("#name").fill("原创任务项目")
        page.get_by_role("button", name="创建项目", exact=True).click()
        page.locator("#projects").get_by_role("button", name="原创任务项目", exact=True).click()
        page.locator("nav [data-view='requirements']").click()
        page.locator("#requirement-title").fill("人工原创需求")
        page.locator("#requirement-text").fill("生成一份原创候选文件")
        page.locator("#acceptance-text").fill("由独立验收检查内容")
        page.locator("#confirmed").check()
        page.get_by_role("button", name="保存需求新修订", exact=True).click()
        expect(page.locator("#requirement-state")).to_contain_text("已保存 v1")
        page.locator("nav [data-view='tasks']").click()
        page.locator("#task-goal").fill("original-browser-candidate")
        page.get_by_role("button", name="创建执行任务", exact=True).click()
        page.locator("#execution-tasks").get_by_role("button", name="启动任务", exact=True).click()
        expect(page.locator("#run-status")).to_contain_text("候选已返回", timeout=15000)
        expect(page.locator("#run-status")).to_contain_text("未验收")
        expect(page.locator("#run-events")).to_contain_text("真实工具退出码：0")
        page.get_by_role("button", name="查证 Runner", exact=True).click()
        expect(page.locator("#runner-facts")).to_contain_text("FINISHED")
        expect(page.locator("#runner-facts")).to_contain_text("退出码 0")
        before = page.locator("#run-events").inner_text()
        with page.expect_event("requestfailed", predicate=lambda request: "/events?" in request.url, timeout=10000):
            context.set_offline(True)
        context.set_offline(False)
        page.reload()
        expect(page.locator("#run-status")).to_contain_text("候选已返回", timeout=15000)
        expect(page.locator("#run-events")).to_contain_text("真实工具退出码：0")
        lines = page.locator("#run-events").inner_text().splitlines()
        numbers = [int(line.split(" · ")[0]) for line in lines]
        assert len(numbers) == len(set(numbers))
        assert numbers == sorted(numbers)
        assert any(int(parse_qs(urlparse(url).query)["after"][0]) > 0 for url in event_requests)
        assert not errors
        browser.close()


